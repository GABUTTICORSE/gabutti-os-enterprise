const assert = require('assert');
const { runInboxCreatedAutomation } = require('../inbox_automation');
let counter = 0;
const uid = prefix => `${prefix}_${++counter}`;
const log = (db, action, entity, detail) => db.activity.unshift({action,entity,detail});
const db = {clients:[],tasks:[],commercial_processes:[],inbox_analysis:[],activity:[]};
const inbox = {id:'inb_test',source:'Gmail',sender:'Mario Rossi',email:'mario@example.com',whatsapp:'+56 9 1234 5678',message:'Necesito cotización casco Bell HP10 talla M',owner:'Andrea',status:'Nuevo'};
const result = runInboxCreatedAutomation(db,inbox,{uid,log});
assert.equal(db.clients.length,1);
assert.equal(db.commercial_processes.length,1);
assert.equal(db.tasks.length,1);
assert.equal(db.inbox_analysis.length,1);
assert.equal(inbox.status,'Convertido');
assert.equal(result.client.email,'mario@example.com');
assert.equal(result.commercialProcess.clientId,result.client.id);
runInboxCreatedAutomation(db,inbox,{uid,log});
assert.equal(db.clients.length,1,'No debe duplicar cliente');
assert.equal(db.commercial_processes.length,1,'No debe duplicar proceso');
console.log('OK inbox flow');
